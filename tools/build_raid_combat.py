"""Export the existing combat formula and species metadata for the standalone server."""
import ast
import json
from pathlib import Path

from tuipet import data

root = Path(__file__).resolve().parents[1]
source = (root / 'src/tuipet/battle.py').read_text(encoding='utf-8')
tree = ast.parse(source)
parts = []
for node in tree.body:
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name in ('_tri', 'Side', 'generate_raid'):
        if node.name == 'Side':
            node.body = [n for n in node.body if not isinstance(n, ast.FunctionDef) or n.name != 'of_pet']
        parts.append(ast.unparse(node))
header = '''# Generated by tools/build_raid_combat.py; regenerate after combat changes.
import json
import random
from pathlib import Path
from types import SimpleNamespace

HP = 5
ROUNDS_RAID = 10
RAID_PLAYER_HP = 10
POWER_HIT_CAP = 0.05
POWER_HIT_PER_POINT = 0.002
_RANK = {"Egg": 0, "Fresh": 1, "InTraining": 2, "Rookie": 3,
         "Champion": 4, "Ultimate": 5, "Mega": 6}
with open(Path(__file__).with_name("raid_species.json"), encoding="utf-8") as f:
    SPECIES = json.load(f)
data = SimpleNamespace(record_for=lambda num: SPECIES.get(str(num), {}))

'''
footer = '''

def volley(save, boss_num, rng=None):
    num = save.get("num")
    if type(num) is not int or str(num) not in SPECIES:
        raise ValueError("unknown cloud species")
    rec = SPECIES[str(num)]
    if rec["stage"] not in ("InTraining", "Rookie", "Champion", "Ultimate", "Mega") or save.get("dead") or save.get("asleep"):
        raise ValueError("pet unavailable")
    def number(key, default, lo=0, hi=999999):
        value = save.get(key, default)
        if not isinstance(value, (int, float)) or not __import__("math").isfinite(value):
            raise ValueError("invalid cloud stat")
        return max(lo, min(hi, value))
    me = Side(num, name=rec["name"], stage=rec["stage"], attribute=rec["attribute"],
              strength=number("strength", 4, hi=4), hunger=number("hunger", 4, hi=4),
              energy=number("energy", 0, hi=rec["max_energy"]), energy_max=rec["max_energy"],
              weight=number("weight", rec["base_weight"]), base_weight=rec["base_weight"],
              trainings_cur=number("stage_trainings", 0), trainings_total=number("total_trainings", 0),
              battles=number("battles", 0), wins=number("wins", 0),
              hit_type=save.get("saved_hit_type", "normal"),
              powers={"Vaccine": number("vaccine", 0), "Data": number("data_power", 0),
                      "Virus": number("virus", 0)})
    return generate_raid(me, Side.wild(boss_num, boss=True), rng=rng)[1], num
'''
(root / 'server/raid_combat.py').write_text(header + '\n\n'.join(parts) + footer, encoding='utf-8')
req = data.load_requirements()
# The stage multiplier catalog covers every fighting-stage species, including x1.
nums = set(req)
nums.update(int(k) for k in json.loads((root / 'server/raid_stage_mult.json').read_text(encoding='utf-8')))
records = {}
for num in sorted(nums):
    rec = data.record_for(num)
    if rec:
        records[str(num)] = {k: rec.get(k, '') for k in ('name', 'stage', 'attribute')}
        records[str(num)].update(base_weight=req.get(num, {}).get('base_weight', 20),
                                 max_energy=req.get(num, {}).get('max_energy', 24))
(root / 'server/raid_species.json').write_text(json.dumps(records, separators=(',', ':')) + '\n', encoding='utf-8')
